import { readdir, readFile, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";

const PROJECT_ROOT = process.cwd();
const SOURCE_ROOT = resolve(PROJECT_ROOT, "src");
const ROUTES_DIRECTORY = resolve(SOURCE_ROOT, "routes");
const GENERATED_ROUTE_TREE = resolve(SOURCE_ROOT, "routeTree.gen.ts");
const ROUTE_PATTERN = /export\s+const\s+Route\s*=\s*createFileRoute\(\s*(["'`])([^"'`]+)\1\s*\)/m;
const CREATE_FILE_ROUTE_CALL_PATTERN = /\bcreateFileRoute\s*\(/m;
const CHECK_ONLY = process.argv.includes("--check");

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(path)));
      continue;
    }

    if (!entry.isFile() || !/\.(?:ts|tsx)$/.test(entry.name) || entry.name === "__root.tsx") {
      continue;
    }

    files.push(path);
  }

  return files;
}

function quote(value) {
  return `'${value.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;
}

function routeIdentifier(routePath) {
  if (routePath === "/") return "IndexRoute";

  const words = routePath
    .replaceAll("$", "")
    .replaceAll(".", " Dot ")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1));

  return `${words.join("")}Route`;
}

function importPath(filePath) {
  const sourceRelative = relative(SOURCE_ROOT, filePath)
    .replaceAll("\\", "/")
    .replace(/\.(?:ts|tsx)$/, "");
  return `./${sourceRelative}`;
}

function expectedRoutePath(filePath) {
  const routeRelative = relative(ROUTES_DIRECTORY, filePath)
    .replaceAll("\\", "/")
    .replace(/\.(?:ts|tsx)$/, "")
    .replaceAll("[.]", ".");
  const segments = routeRelative.split("/").filter(Boolean);

  if (segments.at(-1) === "index") segments.pop();
  return segments.length === 0 ? "/" : `/${segments.join("/")}`;
}

function displayPath(filePath) {
  return relative(PROJECT_ROOT, filePath).replaceAll("\\", "/");
}

async function discoverRoutes() {
  const files = await walk(ROUTES_DIRECTORY);
  const routes = [];

  for (const file of files) {
    const source = await readFile(file, "utf8");
    const hasFileRouteCall = CREATE_FILE_ROUTE_CALL_PATTERN.test(source);
    const match = source.match(ROUTE_PATTERN);

    if (!match?.[2]) {
      if (hasFileRouteCall) {
        throw new Error(
          `A rota em ${displayPath(file)} deve declarar createFileRoute com um caminho literal.`,
        );
      }
      continue;
    }

    const expectedPath = expectedRoutePath(file);
    if (match[2] !== expectedPath) {
      throw new Error(
        `Caminho incompatível em ${displayPath(file)}: encontrado ${match[2]}, esperado ${expectedPath}.`,
      );
    }

    routes.push({
      path: match[2],
      importPath: importPath(file),
      identifier: routeIdentifier(match[2]),
      file,
    });
  }

  routes.sort((left, right) => left.path.localeCompare(right.path, "en"));

  const paths = new Set();
  const identifiers = new Set();
  for (const route of routes) {
    if (paths.has(route.path)) {
      throw new Error(`Rota duplicada detectada: ${route.path}`);
    }
    if (identifiers.has(route.identifier)) {
      throw new Error(`Identificador de rota duplicado: ${route.identifier}`);
    }
    paths.add(route.path);
    identifiers.add(route.identifier);
  }

  return routes;
}

function generateRouteTree(routes) {
  const imports = routes
    .map((route) => `import { Route as ${route.identifier}Import } from ${quote(route.importPath)}`)
    .join("\n");

  const routeDefinitions = routes
    .map(
      (route) => `const ${route.identifier} = ${route.identifier}Import.update({
  id: ${quote(route.path)},
  path: ${quote(route.path)},
  getParentRoute: () => rootRouteImport,
} as any)`,
    )
    .join("\n\n");

  const routeMap = routes
    .map((route) => `  ${quote(route.path)}: typeof ${route.identifier}`)
    .join("\n");
  const moduleRoutes = routes
    .map(
      (route) => `    ${quote(route.path)}: {
      id: ${quote(route.path)}
      path: ${quote(route.path)}
      fullPath: ${quote(route.path)}
      preLoaderRoute: typeof ${route.identifier}Import
      parentRoute: typeof rootRouteImport
    }`,
    )
    .join("\n");
  const rootChildren = routes.map((route) => `  ${route.identifier},`).join("\n");

  return `/* eslint-disable */

// @ts-nocheck

// noinspection JSUnusedGlobalSymbols

// This file is generated by scripts/generate-route-tree.mjs.
// Do not edit it manually.

import { Route as rootRouteImport } from './routes/__root'
${imports}

${routeDefinitions}

type RouteMap = {
${routeMap}
}

type RoutePath = keyof RouteMap
type FileRoutesByFullPath = RouteMap
type FileRoutesByTo = RouteMap
type FileRoutesById = { __root__: typeof rootRouteImport } & RouteMap

interface FileRouteTypes {
  fileRoutesByFullPath: FileRoutesByFullPath
  fullPaths: RoutePath
  fileRoutesByTo: FileRoutesByTo
  to: RoutePath
  id: '__root__' | RoutePath
  fileRoutesById: FileRoutesById
}

declare module '@tanstack/react-router' {
  interface FileRoutesByPath {
${moduleRoutes}
  }
}

const rootRouteChildren = {
${rootChildren}
}

export const routeTree = rootRouteImport
  ._addFileChildren(rootRouteChildren)
  ._addFileTypes<FileRouteTypes>()
`;
}

const routes = await discoverRoutes();
if (routes.length === 0) {
  throw new Error("Nenhuma rota TanStack foi encontrada em src/routes.");
}

const generated = generateRouteTree(routes);
let current = "";
try {
  current = await readFile(GENERATED_ROUTE_TREE, "utf8");
} catch {
  // The first generation creates the file.
}

if (current === generated) {
  console.log(`[routes] Árvore atualizada: ${routes.length} rotas.`);
  process.exit(0);
}

if (CHECK_ONLY) {
  console.error(
    `[routes] routeTree.gen.ts está desatualizado. Execute: node scripts/generate-route-tree.mjs`,
  );
  process.exit(1);
}

await writeFile(GENERATED_ROUTE_TREE, generated, "utf8");
console.log(`[routes] routeTree.gen.ts regenerado com ${routes.length} rotas.`);
